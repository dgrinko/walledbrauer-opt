"""Independent reproduction of Table 2 (Sect. 7.4): optimal deterministic sequential superchannel (quantum comb)
implementing f(U) = U^T or U^{-1} from n calls to a black-box d-dimensional unitary U.

Formulation (standard normalisation, Chiribella et al.):
  maximise   (1/d^2) Tr[C X_I],   X_I = |I>><<I|_{I1 O1} ... |I>><<I|_{In On} (x) |I>><<I|_{P F}
  subject to C >= 0,  Tr_F C = C^(n) (x) I_{On},  Tr_{Ik} C^(k) = C^(k-1) (x) I_{O(k-1)},  Tr_{I1} C^(1) = I_P,
             with C^(k-1) = (1/d) Tr_{Ik O(k-1)} C^(k).
By covariance, WLOG C commutes with W^{(x)n}_O (x) Wbar_P (x) V^{(x)n}_I (x) Vbar_F   (transposition)
                               or with W^{(x)n+1}_{O^n P} (x) V^{(x)n+1}_{I^n F}            (inversion),
and then the Haar-averaged fidelity equals the U = I value above.
So C = sum_{a,b} c_ab psi(sigma_a) (x) psi(tau_b) with sigma, tau walled Brauer diagrams (B_{n,1} or B_{n+1,0}).
Every (partial) trace is evaluated diagrammatically; operator equalities are imposed through Hilbert-Schmidt
inner products with all diagrams (Gram matrices d^{#cycles}), which is valid for any d (no faithfulness needed).
Positivity is imposed on the compressions of C to V_lambda (x) V_mu, where V_lambda is the cyclic submodule
generated by one vector in the range of a primitive idempotent (any vector works -> basis independent).
"""
