# ---------------------------------------------------------------- diagram operations (k nodes, 2k points)

def flip(m):
    k = len(m) // 2
    sw = lambda x: x + k if x < k else x - k
    return tuple(sw(m[sw(x)]) for x in range(2 * k))


def contract(m, j):
    """Join top node j with bottom node j (partial trace over system j). Returns (diagram on k-1 nodes, loops)."""
    k = len(m) // 2
    t, b = j, k + j
    if m[t] == b:
        loops = 1
        pairs = [(x, m[x]) for x in range(2 * k) if x not in (t, b) and x < m[x]]
    else:
        loops = 0
        u, v = m[t], m[b]
        pairs = [(x, m[x]) for x in range(2 * k) if x not in (t, b, u, v) and x < m[x]] + [(u, v)]

    def remap(x):
        if x < k:
            return x if x < j else x - 1
        y = x - k
        return (k - 1) + (y if y < j else y - 1)
    new = [None] * (2 * (k - 1))
    for x, y in pairs:
        rx, ry = remap(x), remap(y)
        new[rx], new[ry] = ry, rx
    return tuple(new), loops


def insert_identity(m, j):
    """Insert a through-line at node position j (tensor with identity on that system)."""
    k = len(m) // 2

    def remap(x):
        if x < k:
            return x if x < j else x + 1
        y = x - k
        return (k + 1) + (y if y < j else y + 1)
    new = [None] * (2 * (k + 1))
    for x in range(2 * k):
        new[remap(x)] = remap(m[x])
    new[j], new[k + 1 + j] = k + 1 + j, j
    return tuple(new)


def hs(a, b, d):
    """Tr(psi(a)^T psi(b)) = d^{#cycles}."""
    m, l = compose(flip(a), b)
    return d ** (l + num_loops_trace(m))


# ---------------------------------------------------------------- linear maps between diagram spaces

def op_matrix(src, dst, fn):
    """Matrix of a linear map diagrams(src) -> span(diagrams(dst)), fn(diagram) -> (diagram, coeff)."""
    idx = {m: i for i, m in enumerate(dst)}
    M = np.zeros((len(dst), len(src)))
    for j, m in enumerate(src):
        r, c = fn(m)
        M[idx[r], j] += c
    return M


def gram(diags, d):
    return np.array([[hs(a, b, d) for b in diags] for a in diags], dtype=float)


def independent_subset(diags, d):
    G = gram(diags, d)
    keep = []
    for i in range(len(diags)):
        cand = keep + [i]
        if np.linalg.matrix_rank(G[np.ix_(cand, cand)], tol=1e-8) == len(cand):
            keep = cand
    return keep


# ---------------------------------------------------------------- irreducible compressions

def irreps(p, q, d, diags):
    fname = 'primitive_%d_%d.txt' % (p, q) if d >= p + q else 'primitive_%d_%d_%d.txt' % (p, q, d)
    db = parse_db(open(os.path.join(DB, fname)).read(), Algebra(p, q, d), Fraction(d), Fraction(1))
    mats = [psi_matrix(m, d) for m in diags]
    rng = np.random.default_rng(5)
    leaves = {}
    for T in db:
        leaves.setdefault(T[-1], []).append(T)
    reps = []
    for lam, Ts in leaves.items():
        Pi = sum(float(c) * psi_matrix(m, d) for m, c in db[Ts[0]].c.items())
        w = Pi @ rng.normal(size=Pi.shape[0])
        K = np.array([M @ w for M in mats]).T
        U, s, _ = np.linalg.svd(K, full_matrices=False)
        r = int((s > 1e-8 * s[0]).sum())
        assert r == len(Ts), (lam, r, len(Ts))          # cyclic module has dimension d_lambda
        Q = U[:, :r]
        reps.append((lam, [Q.T @ M @ Q for M in mats]))
    return reps


# ---------------------------------------------------------------- the SDP

def solve(task, n, d, verbose=False):
    """The comb SDP with the irreducible blocks X_{lam,mu} (symmetric PSD) as the variables.

    With rho(sigma) = (+)_lam R_lam(sigma) (an isomorphism A -> (+)_lam M_{d_lam}, matrix Rmat in coordinates),
    C = sum Cm[a,b] psi(a) (x) psi(b) has blocks X_{lam,mu}[(i,k),(j,l)] = Xt[(lam,i,j),(mu,k,l)] with
    Xt = Rmat Cm Rmat^T, i.e. Cm = Rinv Xt Rinv^T. Positivity is then just X_{lam,mu} >= 0, and C = C^T is
    X_{lam,mu} symmetric. Equalities are dense rows in the entries of the X's (row-reduced by SVD).
    """
    t0 = time.time()
    pO, qO = (n, 1) if task == 'transpose' else (n + 1, 0)
    full = all_diagrams(pO, qO)
    keep = independent_subset(full, d)
    basis = [full[i] for i in keep]
    N = len(basis)
    reps = irreps(pO, qO, d, basis)
    dims = [Ra[0].shape[0] for _, Ra in reps]
    assert sum(x * x for x in dims) == N
    Rmat = np.array([np.concatenate([Ra[a].ravel() for _, Ra in reps]) for a in range(N)]).T
    Rinv = np.linalg.inv(Rmat)
    offs = np.cumsum([0] + [x * x for x in dims])
    # variables and the map vec_F(Xt) <- entries of the X blocks
    X = {}
    pos = {}          # flat index of Xt (F order) -> (block, row, col)
    for a_, da in enumerate(dims):
        for b_, db_ in enumerate(dims):
            X[a_, b_] = cp.Variable((da * db_, da * db_), PSD=True)
            for i in range(da):
                for j in range(da):
                    for k in range(db_):
                        for l in range(db_):
                            r_ = offs[a_] + i * da + j
                            c_ = offs[b_] + k * db_ + l
                            pos[r_ + c_ * N] = ((a_, b_), i * db_ + k, j * db_ + l)
    order = sorted(pos)
    assert order == list(range(N * N))
    keys = list(X)
    # flat variable vector v = concat_F vec_F(X[key]); index of X[key][r, c]
    base = {}
    off = 0
    for key in keys:
        base[key] = off
        off += X[key].shape[0] ** 2
    perm = np.array([base[pos[t][0]] + pos[t][1] + pos[t][2] * X[pos[t][0]].shape[0] for t in range(N * N)])
    v = cp.hstack([cp.vec(X[key], order='F') for key in keys])

    def lin(Lrow, Rcol):
        """vec_F(Lrow Cm Rcol^T) = M v  with Cm = Rinv Xt Rinv^T."""
        K = np.kron(Rcol @ Rinv, Lrow @ Rinv)          # acts on vec_F(Xt)
        M = np.zeros((K.shape[0], off))
        np.add.at(M.T, perm, K.T)                     # scatter columns of K to the variable layout
        return M

    rows, rhs = [], []

    def diags_of(nprimal_O, has_dual):
        if task == 'transpose':
            return all_diagrams(nprimal_O, 1 if has_dual else 0)
        return all_diagrams(nprimal_O + (1 if has_dual else 0), 0)

    dOP, dIF = full, full
    L = np.zeros((len(full), N))
    for a, i in enumerate(keep):
        L[i, a] = 1.0
    R = L.copy()

    def eq_zero(Lmat, Rmat_, dl, dr):
        A, B = gram(dl, d) @ Lmat, gram(dr, d) @ Rmat_
        _, sa, va = np.linalg.svd(A, full_matrices=False)
        _, sb, vb = np.linalg.svd(B, full_matrices=False)
        A, B = va[sa > 1e-10 * sa.max()], vb[sb > 1e-10 * sb.max()]
        rows.append(lin(A, B))
        rhs.append(np.zeros(A.shape[0] * B.shape[0]))

    nO, nI, hasF = n, n, True
    for step in range(n + 1):
        jIF = nI if hasF else nI - 1
        dIF_new = diags_of(nI if hasF else nI - 1, False)
        trIF = op_matrix(dIF, dIF_new, lambda m: (lambda r: (r[0], d ** r[1]))(contract(m, jIF)))
        if step < n:
            jO = nO - 1
            insr = op_matrix(dOP, dOP, lambda m: (lambda r: (insert_identity(r[0], jO), d ** r[1]))(contract(m, jO)))
            eq_zero((np.eye(len(dOP)) - insr / d) @ L, trIF @ R, dOP, dIF_new)
            dOP_new = diags_of(nO - 1, True)
            trO = op_matrix(dOP, dOP_new, lambda m: (lambda r: (r[0], d ** r[1]))(contract(m, jO)))
            L, R = trO @ L / d, trIF @ R
            dOP, dIF = dOP_new, dIF_new
            nO -= 1
            if hasF:
                hasF = False
            else:
                nI -= 1
        else:
            R = trIF @ R
            assert len(dOP) == 1 and len(dIF_new) == 1
            rows.append(lin(L[:1], R[:1]))
            rhs.append(np.ones(1))
    E, b = np.vstack(rows), np.concatenate(rhs)
    U_, s_, Vt = np.linalg.svd(E, full_matrices=False)
    r = int((s_ > 1e-9 * s_.max()).sum())
    bt = U_.T @ b
    assert np.allclose(bt[r:], 0, atol=1e-8), 'inconsistent equality constraints'
    cons = [Vt[:r] @ v == bt[:r] / s_[:r]]
    Obj = np.array([[hs(bb, a, d) for bb in basis] for a in basis]) / d ** 2
    cobj = np.zeros(off)
    np.add.at(cobj, perm, (Rinv.T @ Obj @ Rinv).ravel(order='F'))
    prob = cp.Problem(cp.Maximize(cobj @ v), cons)
    try:
        prob.solve(solver=cp.CLARABEL, verbose=verbose)
        if prob.status not in ('optimal', 'optimal_inaccurate'):
            raise cp.error.SolverError(prob.status)
    except cp.error.SolverError:
        prob.solve(solver=cp.SCS, eps=1e-8, max_iters=50000, verbose=verbose)
    return prob.value, N, time.time() - t0, prob.status, prob.solver_stats.solver_name


