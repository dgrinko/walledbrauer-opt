DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'wba_idempotents_db')


# ---------------------------------------------------------------- diagram operations (k nodes, 2k points)

def flip(m):
    k = len(m) // 2
    sw = lambda x: x + k if x < k else x - k
    return tuple(sw(m[sw(x)]) for x in range(2 * k))


def contract(m, j):
    """Join top node j with bottom node j (partial trace over system j). Returns (diagram on k-1 nodes, loops)."""
    k = len(m) // 2
    t, b = j, k + j
    if m[t] == b:
        loops = 1
        pairs = [(x, m[x]) for x in range(2 * k) if x not in (t, b) and x < m[x]]
    else:
        loops = 0
        u, v = m[t], m[b]
        pairs = [(x, m[x]) for x in range(2 * k) if x not in (t, b, u, v) and x < m[x]] + [(u, v)]

    def remap(x):
        if x < k:
            return x if x < j else x - 1
        y = x - k
        return (k - 1) + (y if y < j else y - 1)
    new = [None] * (2 * (k - 1))
    for x, y in pairs:
        rx, ry = remap(x), remap(y)
        new[rx], new[ry] = ry, rx
    return tuple(new), loops


def insert_identity(m, j):
    """Insert a through-line at node position j (tensor with identity on that system)."""
    k = len(m) // 2

    def remap(x):
        if x < k:
            return x if x < j else x + 1
        y = x - k
        return (k + 1) + (y if y < j else y + 1)
    new = [None] * (2 * (k + 1))
    for x in range(2 * k):
        new[remap(x)] = remap(m[x])
    new[j], new[k + 1 + j] = k + 1 + j, j
    return tuple(new)


def hs(a, b, d):
    """Tr(psi(a)^T psi(b)) = d^{#cycles}."""
    m, l = compose(flip(a), b)
    return d ** (l + num_loops_trace(m))


# ---------------------------------------------------------------- linear maps between diagram spaces

def op_matrix(src, dst, fn):
    """Matrix of a linear map diagrams(src) -> span(diagrams(dst)), fn(diagram) -> (diagram, coeff)."""
    idx = {m: i for i, m in enumerate(dst)}
    M = np.zeros((len(dst), len(src)))
    for j, m in enumerate(src):
        r, c = fn(m)
        M[idx[r], j] += c
    return M


def gram(diags, d):
    return np.array([[hs(a, b, d) for b in diags] for a in diags], dtype=float)


def independent_subset(diags, d):
    G = gram(diags, d)
    keep = []
    for i in range(len(diags)):
        cand = keep + [i]
        if np.linalg.matrix_rank(G[np.ix_(cand, cand)], tol=1e-8) == len(cand):
            keep = cand
    return keep


# ---------------------------------------------------------------- irreducible compressions

def irreps(p, q, d, diags):
    fname = 'primitive_%d_%d.txt' % (p, q) if d >= p + q else 'primitive_%d_%d_%d.txt' % (p, q, d)
    db = parse_db(open(os.path.join(DB, fname)).read(), Algebra(p, q, d), Fraction(d), Fraction(1))
    mats = [psi_matrix(m, d) for m in diags]
    rng = np.random.default_rng(5)
    leaves = {}
    for T in db:
        leaves.setdefault(T[-1], []).append(T)
    reps = []
    for lam, Ts in leaves.items():
        Pi = sum(float(c) * psi_matrix(m, d) for m, c in db[Ts[0]].c.items())
        w = Pi @ rng.normal(size=Pi.shape[0])
        K = np.array([M @ w for M in mats]).T
        U, s, _ = np.linalg.svd(K, full_matrices=False)
        r = int((s > 1e-8 * s[0]).sum())
        assert r == len(Ts), (lam, r, len(Ts))          # cyclic module has dimension d_lambda
        Q = U[:, :r]
        reps.append((lam, [Q.T @ M @ Q for M in mats]))
    return reps


# ---------------------------------------------------------------- the SDP

def solve(task, n, d, verbose=False):
    t0 = time.time()
    if task == 'transpose':
        pO, qO = n, 1            # O_1..O_n | P
        P_node = n
    else:
        pO, qO = n + 1, 0        # O_1..O_n, P all primal
        P_node = n
    full = all_diagrams(pO, qO)
    keep = independent_subset(full, d)
    basis = [full[i] for i in keep]
    N = len(basis)
    # C = sum Cm[a,b] psi(basis_a)_{OP} (x) psi(basis_b)_{IF}.  WLOG C = C^T: with Phi the matrix of the flip
    # (transpose) sigma -> sigma^* in basis coordinates, C^T has coefficients Phi Cm Phi^T, so we parametrise
    # exactly the invariant subspace Cm = W+ K++ W+^T + W- K-- W-^T (W+- span the +-1 eigenspaces of Phi).
    Gb = gram(basis, d)
    H = np.array([[hs(basis[c], flip(basis[a]), d) for a in range(N)] for c in range(N)])
    Phi = np.linalg.solve(Gb, H)
    assert np.allclose(Phi @ Phi, np.eye(N), atol=1e-8)
    def span(P):
        u, s_, _ = np.linalg.svd(P)
        return u[:, s_ > 1e-8]
    Wp, Wm = span((np.eye(N) + Phi) / 2), span((np.eye(N) - Phi) / 2)
    Kp = cp.Variable((Wp.shape[1], Wp.shape[1]))
    Km = cp.Variable((Wm.shape[1], Wm.shape[1])) if Wm.shape[1] else None
    Cm = Wp @ Kp @ Wp.T + (Wm @ Km @ Wm.T if Km is not None else 0)
    cons = []

    # node bookkeeping: OP side nodes = [O_1..O_n, P]; IF side nodes = [I_1..I_n, F] (same algebra)
    def diags_of(nprimal_O, has_dual):
        return all_diagrams(nprimal_O, 1 if has_dual else 0) if task == 'transpose' else all_diagrams(nprimal_O + (1 if has_dual else 0), 0)

    # current representation: X = L @ Cm @ R^T  with L: OP-coefficients over dOP, R: IF-coefficients over dIF
    dOP, dIF = full, full
    L = np.zeros((len(full), N))
    for a, i in enumerate(keep):
        L[i, a] = 1.0                        # inclusion of the independent basis into all diagrams
    R = L.copy()

    def eq_zero(Lmat, Rmat, dl, dr):
        """Impose  sum_ab Cm[a,b] (Lmat_:,a  over dl) (x) (Rmat_:,b over dr) == 0  via HS inner products."""
        Gl, Gr = gram(dl, d), gram(dr, d)
        A, B = Gl @ Lmat, Gr @ Rmat
        # drop numerically dependent rows to keep the solver happy
        # replace A, B by orthonormal bases of their row spaces (same constraint, well conditioned)
        _, sa, va = np.linalg.svd(A, full_matrices=False)
        _, sb, vb = np.linalg.svd(B, full_matrices=False)
        A = va[sa > 1e-10 * sa.max()]
        B = vb[sb > 1e-10 * sb.max()]
        return A @ Cm @ B.T == 0

    # --- comb constraints, from the last tooth to the first
    nO = n          # number of O systems still present on the OP side
    nI = n          # number of I systems still present on the IF side
    hasF = True
    for step in range(n + 1):
        # trace the last IF output: F at the first step, then I_nI
        jIF = nI if hasF else nI - 1
        dIF_new = diags_of(nI if hasF else nI - 1, False)
        trIF = op_matrix(dIF, dIF_new, lambda m: (lambda r: (r[0], d ** r[1]))(contract(m, jIF)))
        if step < n:
            # RHS: (1/d) Tr_{O_last} (.) (x) I_{O_last} on the OP side;  O_last is node nO-1
            jO = nO - 1
            insr = op_matrix(dOP, dOP, lambda m: (lambda r: (insert_identity(r[0], jO), d ** r[1]))(contract(m, jO)))
            cons.append(eq_zero((np.eye(len(dOP)) - insr / d) @ L, trIF @ R, dOP, dIF_new))
            # C^(k-1) = (1/d) Tr_{IF last, O_last} C^(k)
            dOP_new = diags_of(nO - 1, True)
            trO = op_matrix(dOP, dOP_new, lambda m: (lambda r: (r[0], d ** r[1]))(contract(m, jO)))
            L = trO @ L / d
            R = trIF @ R
            dOP, dIF = dOP_new, dIF_new
            nO -= 1
            if hasF:
                hasF = False
            else:
                nI -= 1
        else:
            # last tooth: Tr_{I_1} C^(1) = I_P ; OP side is now only P (one node), IF side I_1 -> nothing
            R = trIF @ R
            dIF = dIF_new
            assert len(dOP) == 1 and len(dIF) == 1
            cons.append((L @ Cm @ R.T)[0, 0] == 1)

    # --- objective (1/d^2) Tr[C X_I] = (1/d^2) sum Cm[a,b] Tr(psi(a) psi(b)^T)
    Obj = np.array([[hs(b, a, d) for b in basis] for a in basis]) / d ** 2
    objective = cp.sum(cp.multiply(Obj, Cm))

    # --- positivity on every lambda x mu block
    reps = irreps(pO, qO, d, basis)
    for la, Ra in reps:
        for mu, Rb in reps:
            da, db_ = Ra[0].shape[0], Rb[0].shape[0]
            Fa = np.array([M.ravel() for M in Ra])     # N x da^2
            Fb = np.array([M.ravel() for M in Rb])     # N x db^2
            Z = Fa.T @ Cm @ Fb                         # (da^2) x (db^2): Z[(i,j),(k,l)] = Y[(i,k),(j,l)]
            # permutation  vec(Z) -> vec(Y)
            nY = da * db_
            rows, cols = [], []
            for i in range(da):
                for j in range(da):
                    for k in range(db_):
                        for l in range(db_):
                            rows.append((i * db_ + k) * nY + (j * db_ + l))
                            cols.append((i * da + j) * db_ * db_ + (k * db_ + l))
            S = sps.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(nY * nY, da * da * db_ * db_))
            Y = cp.reshape(S @ cp.reshape(Z, (da * da * db_ * db_,), order='C'), (nY, nY), order='C')
            cons.append((Y + Y.T) / 2 >> 0)   # Y is symmetric up to round-off since C = C^T
    prob = cp.Problem(cp.Maximize(objective), cons)
    try:
        prob.solve(solver=cp.CLARABEL, verbose=verbose)
    except cp.error.SolverError:
        prob.solve(solver=cp.SCS, eps=1e-8, max_iters=100000, verbose=verbose)
    return prob.value, N, time.time() - t0, prob.status, prob.solver_stats.solver_name


